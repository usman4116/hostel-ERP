VOUCHER_STATUS_CHOICES = [
    ('Unpaid', 'Unpaid'),
    ('Paid', 'Paid'),
    ('Overdue', 'Overdue'),
]

class Voucher(models.Model):
    # Autogenerated Voucher Number
    voucher_no = models.CharField(max_length=50, unique=True, blank=True, editable=False)
    student = models.ForeignKey(Student, on_delete=models.CASCADE, related_name="vouchers")
    enrollment_date = models.DateField()
    billing_cycle_start = models.DateField()
    billing_cycle_end = models.DateField()
    due_date = models.DateField()
    rent_amount = models.DecimalField(max_digits=8, decimal_places=2, default=3000.00)
    electricity_charges = models.DecimalField(max_digits=8, decimal_places=2, default=0.00)
    other_charges = models.DecimalField(max_digits=8, decimal_places=2, default=0.00)
    total_amount = models.DecimalField(max_digits=8, decimal_places=2, blank=True, null=True)
    status = models.CharField(max_length=10, choices=VOUCHER_STATUS_CHOICES, default='Unpaid')
    
    # AC Meter Reading Fields
    is_ac_room = models.BooleanField(default=False)
    initial_meter_reading = models.IntegerField(null=True, blank=True)
    final_meter_reading = models.IntegerField(null=True, blank=True)

    created_at = models.DateTimeField(auto_now_add=True)

    def save(self, *args, **kwargs):
        if not self.voucher_no:
            month_str = date.today().strftime("%Y%m")
            count = Voucher.objects.count() + 1
            unique_suffix = uuid.uuid4().hex[:4].upper()
            self.voucher_no = f"VCH-{month_str}-{count:03d}-{unique_suffix}"
            
        # AC electricity calculation
        if self.is_ac_room and self.initial_meter_reading is not None and self.final_meter_reading is not None:
            if self.final_meter_reading >= self.initial_meter_reading:
                company = CompanySettings.objects.first()
                rate = company.ac_unit_rate if company else 0
                
                # Dynamic check for shared room occupancy
                occupancy = Student.objects.filter(room_no=self.student.room_no, leaving_date__isnull=True).count()
                occupancy = max(1, occupancy)
                
                from decimal import Decimal
                total_electricity = Decimal(self.final_meter_reading - self.initial_meter_reading) * rate
                self.electricity_charges = total_electricity / Decimal(occupancy)
        
        self.total_amount = (self.rent_amount or 0) + (self.electricity_charges or 0) + (self.other_charges or 0)
        
        super().save(*args, **kwargs)

        # Automatically update student rent status based on voucher status
        # Since a student may have multiple vouchers, we update rent_status = True
        # if this voucher is Paid. If they have outstanding Unpaid/Overdue vouchers, 
        # we mark rent_status = False. 
        # But a simple rule: if we are saving this voucher as Paid, we assume they paid their current dues.
        if self.status == 'Paid':
            self.student.rent_status = True
            self.student.save()

            # Automate RentPaymentHistory
            RentPaymentHistory.objects.update_or_create(
                student=self.student,
                month=self.billing_cycle_start.strftime("%B %Y"),
                defaults={
                    'amount': self.total_amount,
                    'amount_paid': self.total_amount,
                    'remaining_amount': 0.00,
                    'date_paid': date.today(),
                    'status': 'paid'
                }
            )
        elif self.status in ['Unpaid', 'Overdue']:
            self.student.rent_status = False
            self.student.save()

    def __str__(self):
        return f"Voucher #{self.voucher_no} - {self.student.name} ({self.status})"


