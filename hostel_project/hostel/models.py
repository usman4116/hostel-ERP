class LeaveNotice(models.Model):
    student = models.ForeignKey(Student, on_delete=models.CASCADE, related_name="leave_notices")
    notice_date = models.DateField(auto_now_add=True)
    planned_leaving_date = models.DateField()
    reason = models.TextField(blank=True, null=True)
    status = models.CharField(
        max_length=20,
        choices=[('Pending', 'Pending'), ('Approved', 'Approved'), ('Rejected', 'Rejected')],
        default='Pending'
    )
    created_at = models.DateTimeField(auto_now_add=True)

    @property
    def eligible_for_refund(self):
        if self.notice_date and self.planned_leaving_date:
            return (self.planned_leaving_date - self.notice_date).days >= 30
        return False

    def __str__(self):
        return f"Leave Notice: {self.student.name} for {self.planned_leaving_date}"
