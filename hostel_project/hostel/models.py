class Student(models.Model):
    user = models.OneToOneField(User, on_delete=models.CASCADE)
    name = models.CharField(max_length=100)
    email = models.EmailField(unique=True)
    phone = models.CharField(max_length=15)
    gender = models.CharField(max_length=10)
    address = models.TextField()
    room_no = models.CharField(max_length=10)
    rent_price = models.CharField(max_length=10, default="3000")
    rent_status = models.BooleanField(default=False)
    join_date = models.DateField(auto_now_add=True)
    
    # Enhanced Student Fields - Autogenerated Enrollment Number
    enrollment_no = models.CharField(max_length=50, unique=True, blank=True, null=True, editable=False)
    cnic = models.CharField("CNIC/B-Form", max_length=20, null=True, blank=True)
    leaving_date = models.DateField(null=True, blank=True)
    deposit_amount = models.DecimalField(max_digits=10, decimal_places=2, default=0.00)
    agreement_expiry = models.DateField(null=True, blank=True)
    assigned_warden = models.ForeignKey(User, on_delete=models.SET_NULL, null=True, blank=True, related_name="warden_students")

    def save(self, *args, **kwargs):
        if not self.enrollment_no:
            year_str = date.today().strftime("%Y")
            count = Student.objects.count() + 1
            unique_suffix = uuid.uuid4().hex[:4].upper()
            self.enrollment_no = f"HST-{year_str}-{count:03d}-{unique_suffix}"
        super().save(*args, **kwargs)

    def __str__(self):
        return f"{self.name} ({self.enrollment_no or 'No ID'}) | Room: {self.room_no}"


